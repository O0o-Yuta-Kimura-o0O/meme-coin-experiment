  const html = document.documentElement;
  const supported = new Set(LANGS.map(([code]) => code));
  const params = new URLSearchParams(location.search);
  const store = {
    get() { try { return localStorage.getItem("mk_lang"); } catch { return null; } },
    set(v) { try { localStorage.setItem("mk_lang", v); } catch {} },
  };

  const country = (params.get("country") || html.dataset.country || "").toUpperCase();
  const pick = [params.get("lang"), store.get(), html.dataset.forceLang, COUNTRY_LANG[country], "en"];
  let lang = pick.find((l) => l && supported.has(l));

  const t = (key) => (T[lang] && T[lang][key]) ?? T.en[key] ?? "";
  window.skT = t;

  function apply() {
    html.lang = lang;
    html.dataset.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = t(el.dataset.i18n);
      if (value) el.innerHTML = value;
    });
    document.querySelectorAll("[data-i18n-day]").forEach((el) => {
      el.textContent = t("day").replace("{d}", el.dataset.i18nDay);
    });
  }

  const select = document.getElementById("lang-select");
  if (select) {
    for (const [code, name] of LANGS) select.add(new Option(name, code));
    select.value = lang;
    select.addEventListener("change", () => {
      const from = lang;
      lang = select.value;
      store.set(lang);
      apply();
      if (window.skTrack) window.skTrack("lang_change", { from, to: lang });
    });
  }

  apply();
